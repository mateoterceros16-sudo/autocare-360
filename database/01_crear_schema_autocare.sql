CÓMO EJECUTARLO
- En DataGrip, conectado a la base autocare360 con el usuario autocare_admin.
- Ejecuta el archivo completo (botón ▶ "Execute" con todo seleccionado).
- El backend usa ddl-auto=validate: Hibernate NO crea tablas, solo comprueba
  que estas tablas coincidan con las entidades JPA. Por eso este script es el
  "contrato" físico de la base.

REGLAS DEL NEGOCIO QUE PROTEGE LA BASE
- RF-15: no se duplica la placa ni el VIN (UNIQUE).
- Integridad: todo vehículo pertenece a un cliente existente (FK).
- El kilometraje no puede ser negativo y el año debe ser razonable (CHECK).
===============================================================================
*/

-- -----------------------------------------------------------------------------
-- 0. LIMPIEZA: tablas antiguas que había creado ddl-auto=update en "public"
--    (tenían columnas equivocadas como salary, name, last_name).
-- -----------------------------------------------------------------------------
DROP TABLE IF EXISTS public.vehiculos;
DROP TABLE IF EXISTS public.clientes;

-- -----------------------------------------------------------------------------
-- 1. SCHEMA PROPIO DEL PROYECTO
-- -----------------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS autocare;

-- -----------------------------------------------------------------------------
-- 2. CLIENTE (tabla padre): propietario de los vehículos
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS autocare.cliente (
    id_cliente       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    documento        VARCHAR(30)  NOT NULL,
    nombre_completo  VARCHAR(180) NOT NULL,
    email            VARCHAR(180) NOT NULL,
    telefono         VARCHAR(20),
    activo           BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_registro   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_cliente            PRIMARY KEY (id_cliente),
    CONSTRAINT uq_cliente_documento  UNIQUE (documento),
    CONSTRAINT uq_cliente_email      UNIQUE (email)
);

-- -----------------------------------------------------------------------------
-- 3. VEHICULO (tabla dependiente): cada vehículo tiene UN propietario
--    La FK id_cliente vive AQUÍ, en la tabla N.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS autocare.vehiculo (
    id_vehiculo       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_cliente        BIGINT       NOT NULL,
    placa             VARCHAR(10)  NOT NULL,
    vin               VARCHAR(17),
    marca             VARCHAR(60)  NOT NULL,
    modelo            VARCHAR(60)  NOT NULL,
    anio              INTEGER      NOT NULL,
    kilometraje       INTEGER      NOT NULL,
    tipo_combustible  VARCHAR(20)  NOT NULL,
    fecha_registro    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_vehiculo PRIMARY KEY (id_vehiculo),
    CONSTRAINT fk_vehiculo_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES autocare.cliente (id_cliente),
    CONSTRAINT uq_vehiculo_placa UNIQUE (placa),
    CONSTRAINT uq_vehiculo_vin   UNIQUE (vin),
    CONSTRAINT ck_vehiculo_vin_largo
        CHECK (vin IS NULL OR char_length(vin) = 17),
    CONSTRAINT ck_vehiculo_anio
        CHECK (anio BETWEEN 1950 AND 2100),
    CONSTRAINT ck_vehiculo_kilometraje
        CHECK (kilometraje >= 0),
    CONSTRAINT ck_vehiculo_tipo_combustible
        CHECK (tipo_combustible IN ('GASOLINA', 'DIESEL', 'GAS', 'ELECTRICO', 'HIBRIDO'))
);

-- Índice para buscar rápido los vehículos de un cliente (la FK no crea índice sola)
CREATE INDEX IF NOT EXISTS ix_vehiculo_id_cliente
    ON autocare.vehiculo (id_cliente);

-- -----------------------------------------------------------------------------
-- 4. COMPROBACIÓN
-- -----------------------------------------------------------------------------
SELECT table_schema, table_name
FROM information_schema.tables
WHERE table_schema = 'autocare'
ORDER BY table_name;
